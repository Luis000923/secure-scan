/**
 * Finding Builder
 * Implements the Builder pattern for constructing Finding objects
 * 
 * Provides a fluent API for creating Findings with proper defaults
 * and validation, reducing boilerplate and potential errors.
 */

import { 
  Finding, 
  Severity, 
  ThreatType, 
  FindingCategory, 
  SecurityStandard 
} from '../../types';
import { generateId, extractCodeContext } from '../../utils';
import { getStandardsForThreat } from '../../rules/standards';

/**
 * FindingBuilder Class
 * 
 * Fluent builder for constructing Finding objects with validation.
 * 
 * @example
 * const finding = new FindingBuilder()
 *   .setFile('src/app.js', '/full/path/src/app.js')
 *   .setLocation(42)
 *   .setTitle('SQL Injection Vulnerability')
 *   .setDescription('User input directly concatenated into SQL query')
 *   .setSeverity(Severity.CRITICAL)
 *   .setThreatType(ThreatType.SQL_INJECTION)
 *   .setSnippet('const query = "SELECT * FROM users WHERE id = " + userId;')
 *   .setRemediation('Use parameterized queries or prepared statements')
 *   .setAnalyzer('JavaScript Analyzer')
 *   .build();
 */
export class FindingBuilder {
  private id: string;
  private ruleId?: string;
  private title: string = '';
  private description: string = '';
  private severity: Severity = Severity.INFO;
  private threatType: ThreatType = ThreatType.VULNERABILITY;
  private category: FindingCategory = FindingCategory.VULNERABILITY;
  private file: string = '';
  private fullPath: string = '';
  private startLine: number = 1;
  private endLine: number = 1;
  private startColumn?: number;
  private endColumn?: number;
  private code: string = '';
  private contextBefore: string = '';
  private contextAfter: string = '';
  private standards: SecurityStandard[] = [];
  private remediation: string = 'Review and fix the identified issue.';
  private confidence: number = 75;
  private analyzer: string = 'Unknown';
  private tags: string[] = [];
  private metadata: Record<string, unknown> = {};

  constructor() {
    this.id = generateId();
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // IDENTITY METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set a custom ID (optional - auto-generated by default)
   */
  setId(id: string): FindingBuilder {
    this.id = id;
    return this;
  }

  /**
   * Set the rule ID that triggered this finding
   */
  setRuleId(ruleId: string): FindingBuilder {
    this.ruleId = ruleId;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // DESCRIPTION METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set the finding title (required)
   */
  setTitle(title: string): FindingBuilder {
    this.title = title;
    return this;
  }

  /**
   * Set the detailed description (required)
   */
  setDescription(description: string): FindingBuilder {
    this.description = description;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // CLASSIFICATION METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set the severity level (required)
   */
  setSeverity(severity: Severity): FindingBuilder {
    this.severity = severity;
    return this;
  }

  /**
   * Set the threat type (required)
   */
  setThreatType(threatType: ThreatType): FindingBuilder {
    this.threatType = threatType;
    return this;
  }

  /**
   * Set the finding category
   */
  setCategory(category: FindingCategory): FindingBuilder {
    this.category = category;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // LOCATION METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set the file path (relative and optional full path)
   */
  setFile(relativePath: string, fullPath?: string): FindingBuilder {
    this.file = relativePath;
    this.fullPath = fullPath || relativePath;
    return this;
  }

  /**
   * Set the location (line numbers)
   * @param startLine - Starting line (1-based)
   * @param endLine - Ending line (optional, defaults to startLine)
   */
  setLocation(startLine: number, endLine?: number): FindingBuilder {
    this.startLine = startLine;
    this.endLine = endLine || startLine;
    return this;
  }

  /**
   * Set column positions (optional)
   */
  setColumns(startColumn: number, endColumn?: number): FindingBuilder {
    this.startColumn = startColumn;
    this.endColumn = endColumn || startColumn;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // SNIPPET METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set the code snippet directly
   */
  setSnippet(code: string, contextBefore?: string, contextAfter?: string): FindingBuilder {
    this.code = code;
    this.contextBefore = contextBefore || '';
    this.contextAfter = contextAfter || '';
    return this;
  }

  /**
   * Extract snippet from file content at the specified line
   */
  extractSnippetFromContent(content: string, lineNum: number, contextSize: number = 2): FindingBuilder {
    const context = extractCodeContext(content, lineNum, contextSize);
    this.code = context.code;
    this.contextBefore = context.contextBefore;
    this.contextAfter = context.contextAfter;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // REMEDIATION & STANDARDS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set security standards (auto-derived from threatType if not set)
   */
  setStandards(standards: SecurityStandard[]): FindingBuilder {
    this.standards = standards;
    return this;
  }

  /**
   * Set the remediation guidance
   */
  setRemediation(remediation: string): FindingBuilder {
    this.remediation = remediation;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // METADATA METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Set confidence level (0-100)
   */
  setConfidence(confidence: number): FindingBuilder {
    this.confidence = Math.max(0, Math.min(100, confidence));
    return this;
  }

  /**
   * Set the analyzer name
   */
  setAnalyzer(analyzer: string): FindingBuilder {
    this.analyzer = analyzer;
    return this;
  }

  /**
   * Add tags to the finding
   */
  addTags(...tags: string[]): FindingBuilder {
    this.tags.push(...tags);
    return this;
  }

  /**
   * Set custom metadata
   */
  setMetadata(key: string, value: unknown): FindingBuilder {
    this.metadata[key] = value;
    return this;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // BUILD METHOD
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Build and validate the Finding object
   * @throws Error if required fields are missing
   */
  build(): Finding {
    // Validate required fields
    if (!this.title) {
      throw new Error('FindingBuilder: title is required');
    }
    if (!this.description) {
      throw new Error('FindingBuilder: description is required');
    }
    if (!this.file) {
      throw new Error('FindingBuilder: file path is required');
    }

    // Auto-derive standards from threat type if not explicitly set
    const standards = this.standards.length > 0 
      ? this.standards 
      : getStandardsForThreat(this.threatType);

    // Build the Finding object
    const finding: Finding = {
      id: this.id,
      ruleId: this.ruleId,
      title: this.title,
      description: this.description,
      severity: this.severity,
      threatType: this.threatType,
      category: this.category,
      location: {
        file: this.file,
        startLine: this.startLine,
        endLine: this.endLine,
        startColumn: this.startColumn,
        endColumn: this.endColumn
      },
      snippet: {
        code: this.code,
        contextBefore: this.contextBefore,
        contextAfter: this.contextAfter
      },
      standards,
      remediation: this.remediation,
      confidence: this.confidence,
      analyzer: this.analyzer,
      timestamp: new Date(),
      tags: [...new Set(this.tags)] // Remove duplicates
    };

    return finding;
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // STATIC FACTORY METHODS
  // ═══════════════════════════════════════════════════════════════════════════

  /**
   * Create a pre-configured builder for SQL Injection findings
   */
  static sqlInjection(): FindingBuilder {
    return new FindingBuilder()
      .setThreatType(ThreatType.SQL_INJECTION)
      .setSeverity(Severity.CRITICAL)
      .setCategory(FindingCategory.VULNERABILITY)
      .addTags('injection', 'sql', 'database');
  }

  /**
   * Create a pre-configured builder for XSS findings
   */
  static xss(): FindingBuilder {
    return new FindingBuilder()
      .setThreatType(ThreatType.XSS)
      .setSeverity(Severity.HIGH)
      .setCategory(FindingCategory.VULNERABILITY)
      .addTags('xss', 'injection', 'web');
  }

  /**
   * Create a pre-configured builder for Command Injection findings
   */
  static commandInjection(): FindingBuilder {
    return new FindingBuilder()
      .setThreatType(ThreatType.COMMAND_INJECTION)
      .setSeverity(Severity.CRITICAL)
      .setCategory(FindingCategory.VULNERABILITY)
      .addTags('injection', 'command', 'rce');
  }

  /**
   * Create a pre-configured builder for hardcoded secrets
   */
  static hardcodedSecret(): FindingBuilder {
    return new FindingBuilder()
      .setThreatType(ThreatType.HARDCODED_SECRETS)
      .setSeverity(Severity.HIGH)
      .setCategory(FindingCategory.SECRET)
      .addTags('secret', 'credential', 'hardcoded');
  }

  /**
   * Create a pre-configured builder for weak cryptography findings
   */
  static weakCrypto(): FindingBuilder {
    return new FindingBuilder()
      .setThreatType(ThreatType.WEAK_CRYPTOGRAPHY)
      .setSeverity(Severity.MEDIUM)
      .setCategory(FindingCategory.VULNERABILITY)
      .addTags('crypto', 'weak-algorithm');
  }
}

export default FindingBuilder;
